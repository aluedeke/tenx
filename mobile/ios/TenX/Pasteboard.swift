import UIKit
import UniformTypeIdentifiers

/// The pasteboard in the shape the page's `navigator.clipboard.read()` gives
/// (web/src/lib/native.ts): per item, MIME type → text, or base64 for an
/// image. Read here, the app's "Paste from Other Apps: Allow" setting applies
/// instead of WebKit's Paste bubble on every read. With that setting on
/// "Ask", iOS shows no question for a read the page started: it just hands
/// back nothing, so `blocked` tells the two cases apart.
@MainActor
enum Pasteboard {
    static func items(_ board: UIPasteboard = .general) -> [[String: Any]] {
        (0..<board.numberOfItems).compactMap { index in
            let set = IndexSet(integer: index)
            let utis = board.types(forItemSet: set)?.first ?? []
            var data: [String: String] = [:]
            var types: [String] = []
            func add(_ mime: String, _ value: String) {
                guard data[mime] == nil else { return }
                data[mime] = value
                types.append(mime)
            }
            for uti in utis {
                guard let type = UTType(uti), let raw = board.data(forPasteboardType: uti, inItemSet: set)?.first else { continue }
                if type.conforms(to: .html), let text = String(data: raw, encoding: .utf8) {
                    add("text/html", text)
                } else if type.conforms(to: .plainText) || type.conforms(to: .url), let text = String(data: raw, encoding: .utf8) {
                    add("text/plain", text)
                } else if type.conforms(to: .png) || type.conforms(to: .jpeg) || type.conforms(to: .gif) || type.conforms(to: .webP) {
                    add(type.preferredMIMEType ?? "image/png", raw.base64EncodedString())
                } else if type.conforms(to: .image), let png = UIImage(data: raw)?.pngData() {
                    // HEIC, TIFF and the like: PNG, which the agent can read.
                    add("image/png", png.base64EncodedString())
                }
            }
            return types.isEmpty ? nil : ["types": types, "data": data]
        }
    }

    /// Something is on the pasteboard, but iOS gave none of it to us.
    static func blocked(_ items: [[String: Any]], _ board: UIPasteboard = .general) -> Bool {
        items.isEmpty && (board.hasStrings || board.hasImages || board.hasURLs)
    }

    // MARK: The clipboard sync (web/src/lib/clipsync.ts)

    /// The sync's switch in the app's settings; on unless turned off.
    static let syncKey = "clipboardSync"
    static var syncEnabled: Bool { UserDefaults.standard.object(forKey: syncKey) as? Bool ?? true }

    /// What a password manager marks its copies with (nspasteboard.org):
    /// those stay on the device.
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// The change count, and the text only when the count moved since
    /// `since`: the count reads nothing, so the pasteboard itself is read
    /// once per copy, not once per tick.
    static func peek(since: Int?, _ board: UIPasteboard = .general) -> [String: Any] {
        let count = board.changeCount
        var reply: [String: Any] = ["enabled": syncEnabled, "count": count]
        guard syncEnabled, let since, since != count else { return reply }
        if !concealedTypes.isDisjoint(with: board.types) {
            reply["text"] = NSNull()
        } else if let text = board.string {
            reply["text"] = text
        } else {
            reply["text"] = NSNull()
            // On "Paste from Other Apps: Ask" iOS hands back nothing.
            if board.hasStrings || board.hasURLs { reply["blocked"] = true }
        }
        return reply
    }

    /// Put the Mac's text on the pasteboard unless something was copied since
    /// `ifCount`; the new change count, or nil. Local only: Universal
    /// Clipboard would hand it straight back to the Mac.
    static func write(_ text: String, ifCount: Int, _ board: UIPasteboard = .general) -> Int? {
        guard board.changeCount == ifCount else { return nil }
        board.setItems([[UTType.utf8PlainText.identifier: text]], options: [.localOnly: true])
        return board.changeCount
    }
}
